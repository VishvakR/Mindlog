"""Writes the results as JSON and as the Markdown report in docs/evals/."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

LABELS = {
    "rag": "Plain RAG (vector, similarity only)",
    "vector": "Vector + scoring",
    "hybrid": "Hybrid (vector, BM25, entity)",
    "hybrid_ppr": "Hybrid + PPR",
    "full": "Full (+ themes, rerank, MMR)",
}


def merge(path: Path, suite: str, result: dict[str, Any]) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text()) if path.exists() else {}
    data[suite] = result
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    return data


def _pct(x: float) -> str:
    return f"{100 * x:.1f}"


def _recipes(name: str, r: dict[str, Any]) -> list[str]:
    meta = r["meta"]
    lines = [
        f"### {name}",
        "",
        f"{meta['questions']} questions over {meta['scopes']} scopes, {meta['memories']} memories; "
        f"{meta['note']}",
        "",
        "| Recipe | Turn R@5 | Turn R@10 | Turn NDCG@10 | Session R@5 | Session R@10 "
        "| p50 ms | p95 ms |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for recipe, s in r["recipes"].items():
        t, ss = s["turn"], s["session"]
        cells = [
            _pct(t["recall_any@5"]),
            _pct(t["recall_any@10"]),
            _pct(t["ndcg@10"]),
            _pct(ss["recall_any@5"]),
            _pct(ss["recall_any@10"]),
            f"{s['p50_ms']:.0f}",
            f"{s['p95_ms']:.0f}",
        ]
        lines.append(f"| {LABELS.get(recipe, recipe)} | " + " | ".join(cells) + " |")
    cats = sorted({c for s in r["recipes"].values() for c in s["by_category"]})
    lines += [
        "",
        "Turn recall_any@10 by question category:",
        "",
        "| Recipe | " + " | ".join(cats) + " |",
        "|---|" + "---:|" * len(cats),
    ]
    for recipe, s in r["recipes"].items():
        row = [_pct(s["by_category"].get(c, {}).get("recall_any@10", 0.0)) for c in cats]
        lines.append(f"| {LABELS.get(recipe, recipe)} | " + " | ".join(row) + " |")
    if "packing" in r:
        lines += [
            "",
            "Packing: share of questions with an evidence turn inside the packed context "
            "(tokens used):",
            "",
            "| Recipe | "
            + " | ".join(str(p["budget"]) for p in next(iter(r["packing"].values())))
            + " |",
            "|---|" + "---:|" * len(next(iter(r["packing"].values()))),
        ]
        for recipe, points in r["packing"].items():
            cells = [f"{_pct(p['evidence_packed'])} ({p['tokens_used']:.0f})" for p in points]
            lines.append(f"| {LABELS.get(recipe, recipe)} | " + " | ".join(cells) + " |")
    return [*lines, ""]


def markdown(data: dict[str, Any]) -> str:
    lines = [
        "# Phase 6 retrieval evals",
        "",
        "Generated by `uv run python -m evals.run` (python/evals). Retrieval only: whether recall",
        "puts the evidence turns in its top k (LongMemEval's `recall_any`, binary NDCG), not",
        "answer accuracy.",
        "Percentages; session columns map turns to their sessions first. Latencies are per query,",
        "one query at a time, on a single node with the ONNX model service on the same machine.",
        "",
    ]
    for suite, title in (("longmemeval", "LongMemEval_s"), ("locomo", "LoCoMo")):
        if suite in data:
            lines += _recipes(title, data[suite])
    if "cache" in data:
        c = data["cache"]
        lines += [
            "### Semantic cache",
            "",
            f"{c['stored']} distinct questions stored; {c['positives']} reworded repeats and "
            f"{c['negatives']} different questions looked up.",
            "",
            "| Threshold | Hit rate on repeats | False-positive rate | Wrong share of hits |",
            "|---:|---:|---:|---:|",
        ]
        for p in c["curve"]:
            cells = [
                f"{p['threshold']:.2f}",
                _pct(p["hit_rate"]),
                _pct(p["false_positive_rate"]),
                _pct(p["wrong_share_of_hits"]),
            ]
            lines.append("| " + " | ".join(cells) + " |")
        chosen = c.get("chosen")
        lines += [
            "",
            f"Chosen threshold: {chosen['threshold']:.2f}"
            if chosen
            else "No threshold meets the gate.",
            "",
        ]
    return "\n".join(lines)
